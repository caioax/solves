void drawFont(string s) {
    for (int i = 0; i < 2; i++) {
        bool first = true;
        for (char c : s) {
            c = toupper(c);
            if (!font.count(c))
                continue;

            if (!first)
                cout << ' ';
            first = false;
            cout << font[c][i];
        }
        cout << "\n";
    }
}
